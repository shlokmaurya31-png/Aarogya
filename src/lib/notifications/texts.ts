const RTL = new Set<string>(["ur"]);

/** The language a text is written in: the person's, if it is one of the app's, else English. */
export function textLanguage(language: string | null | undefined): SupportedLanguage {
  return (SUPPORTED_LANGUAGES as readonly string[]).includes(language ?? "") ? (language as SupportedLanguage) : "en";
}

/** "rtl" for Urdu, else "ltr": how a screen sets `dir` on the text. */
export function textDirection(language: string): "rtl" | "ltr" {
  return RTL.has(language) ? "rtl" : "ltr";
}

const TOKEN = /\{(\w+)(?:\|([^|}]*)\|([^|}]*))?\}/g;

/** The value names a template inserts ({name}), not the plural choices. */
export function placeholders(template: string): string[] {
  return [...new Set([...template.matchAll(TOKEN)].filter((m) => m[2] === undefined).map((m) => m[1]))].sort();
}

/** The value names a template's plural choices ({name|one|other}) depend on. */
export function pluralVariables(template: string): string[] {
  return [...new Set([...template.matchAll(TOKEN)].filter((m) => m[2] !== undefined).map((m) => m[1]))].sort();
}

/** Fills a template. A missing value is an error: a text never goes out with a hole in it. */
export function fillTemplate(template: string, values: Record<string, string | number>): string {
  return template.replace(TOKEN, (_, name: string, one?: string, other?: string) => {
    const v = values[name];
    if (v === undefined) throw new Error(`No value for {${name}}`);
    if (one !== undefined) return Number(v) === 1 ? one : other!;
    return String(v);
  });
}

/** One text in the person's language (English when theirs isn't one of the app's), with that language. */
export function messageText(key: TemplateKey, language: string | null | undefined, values: Record<string, string | number> = {}) {
  const lang = textLanguage(language);
  return { language: lang, text: fillTemplate(TEMPLATES[key][lang], values) };
}
