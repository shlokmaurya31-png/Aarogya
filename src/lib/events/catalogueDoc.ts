import type { z } from "zod";
import type { EventContract } from "./types";
import type { DomainEventConsumer } from "./consumers";
import type { FunctionFacts } from "./emitCoverage";

/**
 * Renders docs/EVENT_CATALOGUE.md from the code: every contract in the
 * catalogue (type, version, aggregate, scope, sensitivity, producer, payload
 * fields), the functions that emit it (the emit-coverage static analysis) and
 * the registered consumers that handle it. Pure, so the drift test
 * (catalogueDoc.test.ts) can compare the committed file with a fresh render;
 * regenerate with `npm run docs:events`.
 */

type Def = { type: string; innerType?: z.ZodTypeAny; element?: z.ZodTypeAny; shape?: Record<string, z.ZodTypeAny>; values?: unknown[] };
const def = (s: z.ZodTypeAny) => (s as unknown as { def: Def }).def;

/** One payload field's type as a short, readable string. */
export function describeSchema(s: z.ZodTypeAny): string {
  const d = def(s);
  switch (d.type) {
    case "optional":
    case "nullable":
    case "default":
    case "readonly":
      return describeSchema(d.innerType!);
    case "enum":
      return (s as unknown as { options: string[] }).options.join(" \\| ");
    case "literal":
      return (d.values ?? []).map((v) => JSON.stringify(v)).join(" \\| ");
    case "array":
      return `${describeSchema(d.element!)}[]`;
    case "object":
      return `{ ${Object.entries(d.shape ?? {}).map(([k, v]) => `${k}${fieldFlags(v)}: ${describeSchema(v)}`).join(", ")} }`;
    default:
      return d.type;
  }
}

/** "?" optional, "∅" nullable (both may apply). */
function fieldFlags(s: z.ZodTypeAny): string {
  let flags = "";
  let cur = s;
  for (;;) {
    const d = def(cur);
    if (d.type === "optional" || d.type === "default") flags += flags.includes("?") ? "" : "?";
    else if (d.type === "nullable") flags += flags.includes("∅") ? "" : "∅";
    else if (d.type !== "readonly") return flags;
    cur = d.innerType!;
  }
}

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function consumersOf(type: string, consumers: readonly DomainEventConsumer[]): string[] {
  return consumers.filter((c) => c.handles !== "*" && c.handles.includes(type)).map((c) => c.name).sort();
}

/** Where each event type is emitted from, as "src/lib/…/file.ts#function": direct emit literals plus registered emitting helpers. */
export function emitSites(facts: readonly FunctionFacts[], helpers: Record<string, readonly string[]>): Map<string, string[]> {
  const out = new Map<string, Set<string>>();
  const add = (t: string, key: string) => out.set(t, (out.get(t) ?? new Set()).add(key));
  for (const f of facts) for (const t of f.emitTypes) add(t, f.key);
  for (const [key, types] of Object.entries(helpers)) for (const t of types) add(t, key);
  return new Map([...out].map(([t, keys]) => [t, [...keys].sort()]));
}

export function renderEventCatalogue(contracts: readonly EventContract[], consumers: readonly DomainEventConsumer[], sites: ReadonlyMap<string, readonly string[]>): string {
  const sorted = [...contracts].sort((a, b) => a.type.localeCompare(b.type) || a.version - b.version);
  const types = [...new Set(sorted.map((c) => c.type))];
  const current = new Map<string, number>();
  for (const c of sorted) current.set(c.type, Math.max(current.get(c.type) ?? 0, c.version));
  const everything = consumers.filter((c) => c.handles === "*").map((c) => c.name).sort();
  const bySensitivity = (s: string) => types.filter((t) => sorted.find((c) => c.type === t && c.version === current.get(t))!.sensitivity === s).length;

  const out: string[] = [];
  out.push("# Event catalogue");
  out.push("");
  out.push("<!-- GENERATED by `npm run docs:events` from src/lib/events/catalogue.ts and the registered consumers. Do not edit by hand: catalogueDoc.test.ts fails when this file drifts from the code. -->");
  out.push("");
  out.push(`${types.length} event types, ${sorted.length} contracts (a type gains a version when its contract changes; producers emit the current one, consumers and replay still accept the older ones).`);
  out.push(`Current versions by sensitivity: SENSITIVE ${bySensitivity("SENSITIVE")}, INTERNAL ${bySensitivity("INTERNAL")}, LOW ${bySensitivity("LOW")}.`);
  out.push("");
  out.push(`Every event is also delivered to ${everything.map((n) => `\`${n}\``).join(" and ")} (they handle \`*\`; the workflow engine starts only the workflows whose active definitions trigger on that type and version), so the Consumers column lists the other consumers.`);
  out.push("");
  out.push("Emitted from: the functions that pass the type to an emit call, found by the static analysis behind emitCoverage.test.ts, plus the registered emitting helpers (EMITTING_HELPERS).");
  out.push("");
  out.push("Payload fields: `?` optional, `∅` nullable. Payloads carry identifiers and closed codes only; contracts are `.strict()`, so an unknown key is rejected on emit and on replay.");
  out.push("");
  out.push("## Index");
  out.push("");
  out.push("| Event | Current | Aggregate | Scope | Sensitivity | Consumers |");
  out.push("|---|---|---|---|---|---|");
  for (const t of types) {
    const c = sorted.find((x) => x.type === t && x.version === current.get(t))!;
    const versions = sorted.filter((x) => x.type === t).map((x) => `v${x.version}`).join(", ");
    out.push(`| [${t}](#${t.toLowerCase()}) | ${versions === `v${c.version}` ? `v${c.version}` : `v${c.version} (${versions})`} | ${c.aggregateType} | ${c.scope} | ${c.sensitivity} | ${consumersOf(t, consumers).join(", ") || "—"} |`);
  }
  out.push("");
  out.push("## Contracts");
  for (const t of types) {
    out.push("");
    out.push(`### ${t}`);
    for (const c of sorted.filter((x) => x.type === t)) {
      out.push("");
      out.push(`**v${c.version}**${c.version === current.get(t) ? " (current)" : ""} · aggregate ${[c.aggregateType, ...(c.alternateAggregateTypes ?? [])].join(" / ")} · ${c.scope} · ${c.sensitivity}`);
      out.push("");
      out.push(`Producer: ${esc(c.producer)}`);
      out.push("");
      out.push("| Field | Type |");
      out.push("|---|---|");
      const shape = def(c.payload).shape ?? {};
      for (const [k, v] of Object.entries(shape)) out.push(`| \`${k}\`${fieldFlags(v)} | ${describeSchema(v)} |`);
    }
    out.push("");
    const at = sites.get(t) ?? [];
    out.push(`Emitted from: ${at.length ? at.map((k) => `\`${k}\``).join(", ") : "— (no literal emit site found; see the producer above)"}`);
    out.push("");
    out.push(`Consumers: ${consumersOf(t, consumers).join(", ") || "none beyond the `*` consumers"}`);
  }
  out.push("");
  return out.join("\n");
}
