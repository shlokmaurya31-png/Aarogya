import { NextRequest } from "next/server";
import { requireFacilityStaff } from "@/lib/auth/hospitalRbac";
import { withApiErrors } from "@/lib/auth/rbac";
import { compareQuotations } from "@/lib/hospital/procurement/procurementAdvanced";

export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  return withApiErrors(async () => {
    const { id } = await params;
    const { searchParams } = new URL(req.url);
    const { facilityId } = await requireFacilityStaff("procurement:rfq:manage", searchParams.get("facilityId") ?? undefined);
    return await compareQuotations(id, facilityId);
  });
}
